	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public static char ToCharUpper(int value)
	{
		value &= 0xF;
		value += 48;
		if (value > 57)
		{
			value += 7;
		}
		return (char)value;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public static int FromUpperChar(int c)
	{
		if (c <= 71)
		{
			return CharToHexLookup[c];
		}
		return 255;
	}
